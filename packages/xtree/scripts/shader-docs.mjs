// Generates docs/reference/shaders.md from the chunk sources and credits.json.
// With --check, fails when the checked-in page differs from what would be generated.
import { readFileSync, writeFileSync } from 'node:fs';
import * as prettier from 'prettier';
import {
  families,
  packageRoot,
  parseChunk,
  readChunks,
  repoRoot,
} from './lib.mjs';

const output = `${repoRoot}docs/reference/shaders.md`;
const { entries } = JSON.parse(
  readFileSync(`${packageRoot}credits.json`, 'utf8'),
);
const credits = new Map(entries.map((entry) => [entry.id, entry]));
const chunks = readChunks();
const escape = (text) => text.replace(/\|/g, '\\|');

const lines = [
  '---',
  'outline: [2, 3]',
  '---',
  '',
  '# Shader chunks',
  '',
  '<!-- Generated by packages/xtree/scripts/shader-docs.mjs from packages/xtree/src/shaders. Do not edit; run `pnpm shaders:docs`. -->',
  '',
  'xtree ships its GLSL building blocks as chunks: plain GLSL ES 3.00 strings that you include by id. `resolveIncludes` expands each chunk once, even if several shaders or chunks include it, and adds `#line` directives so compile errors name the chunk.',
  '',
  '```ts',
  "import { resolveIncludes, formatShaderError } from '@mk7s/xtree/glsl';",
  "import { noise } from '@mk7s/xtree/shaders/noise';",
  '',
  'const { code, files } = resolveIncludes(',
  '  `#include <xtree/noise/simplex>',
  '  void main() { gl_FragColor = vec4(vec3(xt_simplex(vUv * 8.0) * 0.5 + 0.5), 1.0); }`,',
  '  noise,',
  "  { name: 'my-effect.glsl' },",
  ');',
  '// Pass `code` to a ShaderMaterial. On a compile error:',
  '// console.error(formatShaderError(gl.getShaderInfoLog(shader), files));',
  '```',
  '',
  'Conventions: every name starts with `xt_` (functions and globals) or `XT_` (macros). Chunks never declare `#version` or `precision`, so the host shader decides those; the functions assume `highp`. Hues are in turns, [0, 1). Includes that are not xtree chunks, such as three.js’s `<common>`, are left for three.js to resolve.',
  '',
];

for (const family of families) {
  const familyChunks = chunks.filter((chunk) => chunk.family === family.id);
  lines.push(
    `## ${family.title}`,
    '',
    `Import from \`@mk7s/xtree/shaders/${family.id}\` as \`${family.id}\`, or every family at once as \`chunks\` from \`@mk7s/xtree/shaders\`.`,
    '',
  );
  for (const chunk of familyChunks) {
    const parsed = parseChunk(chunk.source);
    const credit = credits.get(chunk.id);
    lines.push(
      `### ${chunk.id.split('/').pop()}`,
      '',
      '```glsl',
      `#include <${chunk.id}>`,
      '```',
      '',
      parsed.description,
      '',
    );
    if (parsed.includes.length)
      lines.push(
        `Includes ${parsed.includes.map((id) => `\`${id}\``).join(', ')}.`,
        '',
      );
    const grouped = [];
    for (const fn of parsed.functions) {
      const last = grouped.at(-1);
      if (last && last.name === fn.name && !fn.doc)
        last.signatures.push(fn.signature);
      else
        grouped.push({
          name: fn.name,
          signatures: [fn.signature],
          doc: fn.doc,
        });
    }
    lines.push('| Function | Description |', '| --- | --- |');
    for (const fn of grouped) {
      lines.push(
        `| ${fn.signatures.map((s) => `\`${escape(s)}\``).join('<br>')} | ${escape(fn.doc)} |`,
      );
    }
    lines.push('');
    if (parsed.defines.length) {
      lines.push('| Constant | Value |', '| --- | --- |');
      for (const define of parsed.defines)
        lines.push(`| \`${define.name}\` | \`${escape(define.value)}\` |`);
      lines.push('');
    }
    if (credit) {
      const licence =
        credit.kind === 'original'
          ? 'Original implementation (MIT)'
          : `${credit.kind === 'ported' ? 'Ported' : 'Derived'} from ${credit.notice} (${credit.licence}); see THIRD_PARTY_NOTICES.md`;
      lines.push(
        `**Credits:** ${licence}. References: ${credit.references.join('; ')}.`,
        '',
      );
    }
  }
}

const config = (await prettier.resolveConfig(output)) ?? {};
const content = await prettier.format(lines.join('\n'), {
  ...config,
  filepath: output,
});
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(output, 'utf8');
  } catch {
    /* Missing counts as stale. */
  }
  if (current !== content) {
    console.error(
      'docs/reference/shaders.md is out of date; run `pnpm shaders:docs`.',
    );
    process.exit(1);
  }
  console.log('Shader reference is up to date.');
} else {
  writeFileSync(output, content);
  console.log(`Wrote docs/reference/shaders.md (${chunks.length} chunks).`);
}
