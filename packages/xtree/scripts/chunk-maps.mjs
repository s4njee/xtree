// Generates src/shaders/maps.ts: one ChunkMap per chunk that also contains
// its transitive includes, so code can import exactly the GLSL it needs and
// bundlers drop the rest. With --check, fails when the file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import * as prettier from 'prettier';
import { packageRoot, parseChunk, readChunks } from './lib.mjs';

const output = `${packageRoot}src/shaders/maps.ts`;
const chunks = readChunks();
const byId = new Map(chunks.map((chunk) => [chunk.id, chunk]));
const camel = (id) =>
  id
    .replace(/^xtree\//, '')
    .split(/[/-]/)
    .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join('');
const exportName = (id) => `${camel(id)}Chunks`;
const importName = (id) => `${camel(id)}Source`;

const closure = (id, seen = new Set()) => {
  if (seen.has(id)) return seen;
  for (const dep of parseChunk(byId.get(id).source).includes)
    closure(dep, seen);
  seen.add(id);
  return seen;
};

const lines = [
  '// Generated by scripts/chunk-maps.mjs from the #include graph. Do not edit; run `pnpm chunks`.',
  "import type { ChunkMap } from '../glsl/index.js';",
  ...chunks.map(
    (chunk) =>
      `import ${importName(chunk.id)} from './${chunk.family}/${chunk.file.split('/').pop()}';`,
  ),
  '',
];
for (const chunk of chunks) {
  const ids = [...closure(chunk.id)];
  lines.push(
    `/** \`${chunk.id}\` and the chunks it includes. */`,
    `export const ${exportName(chunk.id)}: ChunkMap = {`,
    ...ids.map((id) => `  '${id}': ${importName(id)},`),
    '};',
    '',
  );
}

const config = (await prettier.resolveConfig(output)) ?? {};
const content = await prettier.format(lines.join('\n'), {
  ...config,
  filepath: output,
});
if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = readFileSync(output, 'utf8');
  } catch {
    /* Missing counts as stale. */
  }
  if (current !== content) {
    console.error('src/shaders/maps.ts is out of date; run `pnpm chunks`.');
    process.exit(1);
  }
  console.log('Chunk maps are up to date.');
} else {
  writeFileSync(output, content);
  console.log(`Wrote src/shaders/maps.ts (${chunks.length} chunk maps).`);
}
